# Лабораторная работа 1, задание 2. Класс «Питомец»
class Pet:
    # атрибут класса: общий для всех питомцев
    category = 'Домашнее животное'
    # словарь «вид → звук», тоже общий для всех объектов
    VOICES = {'кошка': 'Мяу!', 'собака': 'Гав!', 'попугай': 'Кррр!'}

    # конструктор: вызывается автоматически при создании объекта
    def __init__(self, nick, species, years, kilos):
        # атрибуты экземпляра: у каждого питомца свои значения
        self.nick = nick                   # кличка
        self.species = species             # вид
        self.years = years                 # возраст, лет
        self.kilos = kilos                 # вес, кг

    # собираем описание из атрибутов конкретного объекта (self)
    def describe(self):
        return (f'{self.nick} ({self.species}), '
                f'возраст {self.years}, вес {self.kilos} кг')

    # питомец считается взрослым, если ему не меньше 2 лет
    def is_adult(self):
        return self.years >= 2

    def sound(self):
        # get() ищет звук по виду; если вида нет в словаре, вернётся «Молчит»
        return self.VOICES.get(self.species, 'Молчит')


# создаём четыре объекта одного класса с разными данными
home = [
    Pet('Барсик', 'кошка', 4, 5.1),
    Pet('Рекс', 'собака', 6, 18.3),
    Pet('Кеша', 'попугай', 1, 0.12),
    Pet('Спайк', 'ёж', 3, 0.8),            # «ёж» не в словаре → звук «Молчит»
]

# вызываем методы у каждого объекта в цикле
for animal in home:
    # текст статуса выбираем по результату is_adult()
    status = 'взрослый' if animal.is_adult() else 'молодой'
    print(f'{animal.describe()} | {status} | звук: {animal.sound()}')